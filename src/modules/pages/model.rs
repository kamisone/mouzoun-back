//! The page tree (page → sections → items) as the builder edits it, and as revisions store it.

use std::collections::BTreeMap;

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use uuid::Uuid;

use crate::{db::types::TsRange, text_enum};

text_enum!(VisibleOn { All = "all", Desktop = "desktop", Mobile = "mobile" });
text_enum!(SectionCategory {
    Hero = "hero",
    Listing = "listing",
    Content = "content",
    Media = "media",
    SocialProof = "social_proof",
    Conversion = "conversion",
    Layout = "layout",
    Utility = "utility",
});
text_enum!(RevisionStatus {
    Scheduled = "scheduled",
    Published = "published",
    Superseded = "superseded",
    Cancelled = "cancelled",
});
text_enum!(RefType {
    Media = "media",
    Product = "product",
    Category = "category",
    Place = "place",
    Page = "page",
    Faq = "faq",
    Gallery = "gallery",
    Promotion = "promotion",
    Review = "review",
});

impl RefType {
    pub fn parse(s: &str) -> Option<Self> {
        Self::ALL.iter().copied().find(|r| r.as_str() == s)
    }
}

impl PartialOrd for RefType {
    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for RefType {
    fn cmp(&self, other: &Self) -> std::cmp::Ordering {
        self.as_str().cmp(other.as_str())
    }
}

// `text_enum!` cannot carry `#[default]` on a variant.
#[allow(clippy::derivable_impls)]
impl Default for VisibleOn {
    fn default() -> Self {
        Self::All
    }
}

/// Translatable content of a section or an item, one JSON object per locale.
pub type LocalizedContent = BTreeMap<String, Value>;

fn object() -> Value {
    json!({})
}

fn visible() -> bool {
    true
}

/// One section of the draft. Ids are generated by the client (UUIDv7) so a section keeps its
/// identity across autosaves.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct BlockDraft {
    pub id: Uuid,
    #[serde(rename = "type")]
    pub block_type: String,
    #[serde(default)]
    pub name: Option<String>,
    #[serde(default)]
    pub anchor_id: Option<String>,
    #[serde(default = "visible")]
    pub is_visible: bool,
    #[serde(default)]
    pub active_period: Option<TsRange>,
    #[serde(default)]
    pub visible_on: VisibleOn,
    #[serde(default)]
    pub hidden_locales: Vec<String>,
    #[serde(default = "object")]
    pub appearance: Value,
    #[serde(default)]
    pub analytics_label: Option<String>,
    #[serde(default = "object")]
    pub settings: Value,
    #[serde(default)]
    pub content: LocalizedContent,
    #[serde(default)]
    pub items: Vec<ItemDraft>,
    /// A placement of a shared section: its own settings, content and items are ignored.
    #[serde(default)]
    pub shared_block_id: Option<Uuid>,
    /// Read only: the shared section this placement shows (expanded by the API).
    #[serde(default, skip_deserializing, skip_serializing_if = "Option::is_none")]
    pub shared: Option<Box<BlockDraft>>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct ItemDraft {
    pub id: Uuid,
    #[serde(default = "object")]
    pub settings: Value,
    #[serde(default)]
    pub content: LocalizedContent,
    #[serde(default = "visible")]
    pub is_visible: bool,
    #[serde(default)]
    pub active_period: Option<TsRange>,
}

/// Page fields the builder can edit (one entry per locale).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PageText {
    pub title: String,
    pub slug: String,
    #[serde(default)]
    pub excerpt: Option<String>,
    #[serde(default)]
    pub seo_title: Option<String>,
    #[serde(default)]
    pub seo_description: Option<String>,
    #[serde(default)]
    pub og_media_id: Option<Uuid>,
    #[serde(default)]
    pub noindex: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PageHead {
    pub id: Uuid,
    pub page_type: String,
    pub status: String,
    pub cover_media_id: Option<Uuid>,
    pub translations: BTreeMap<String, PageText>,
}

/// `GET /pages/{id}/builder`.
#[derive(Debug, Clone, Serialize)]
pub struct BuilderTree {
    pub page: PageHead,
    pub draft_version: i64,
    pub has_unpublished_changes: bool,
    pub published_revision: Option<i32>,
    pub blocks: Vec<BlockDraft>,
    pub last_saved_by: Option<Editor>,
    pub last_saved_at: Option<DateTime<Utc>>,
}

#[derive(Debug, Clone, Serialize)]
pub struct Editor {
    pub id: Uuid,
    pub name: String,
}

/// `PUT /pages/{id}/builder`.
#[derive(Debug, Clone, Deserialize)]
pub struct SaveTree {
    pub blocks: Vec<BlockDraft>,
    /// Optional page texts (title, SEO) per locale.
    #[serde(default)]
    pub translations: Option<BTreeMap<String, PageText>>,
}

/// What a revision stores: the resolved tree (shared sections inlined), plus the ids it uses.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Snapshot {
    pub format: i32,
    pub page: SnapshotPage,
    pub blocks: Vec<BlockDraft>,
    /// Every referenced entity (media, products...), for "used by a live page" checks.
    pub refs: Vec<RefEntry>,
    /// Data kinds some section resolves by rule ("latest activities"): any change of that kind
    /// may change the page.
    pub rule_sources: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SnapshotPage {
    pub id: Uuid,
    pub page_type: String,
    pub cover_media_id: Option<Uuid>,
    pub translations: BTreeMap<String, PageText>,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct RefEntry {
    pub ref_type: RefType,
    pub ref_id: Uuid,
}

/// A field-level error, addressed by JSON pointer from the tree root.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct FieldError {
    pub path: String,
    pub code: String,
    pub message: String,
}

impl FieldError {
    pub fn new(path: impl Into<String>, code: &str, message: impl Into<String>) -> Self {
        Self {
            path: path.into(),
            code: code.into(),
            message: message.into(),
        }
    }
}
